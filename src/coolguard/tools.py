import ast
import functools
import json
import time
from pathlib import Path

from . import (benchmark, controller, experiments, failure_analysis, paths, remote, runner, runtime, synthetic, verify)

_STAGE_OF = {
    "imread": "load", "imdecode": "load", "resize": "resize", "cvtColor": "grayscale", "GaussianBlur": "blur",
    "medianBlur": "blur", "createCLAHE": "contrast-normalisation", "equalizeHist": "contrast-normalisation",
    "threshold": "binarisation", "adaptiveThreshold": "binarisation", "Canny": "edge-detection", "Sobel": "edge-detection",
    "Laplacian": "edge-detection", "morphologyEx": "morphology", "dilate": "morphology", "erode": "morphology",
    "findContours": "contour-detection", "approxPolyDP": "polygon-approximation", "convexHull": "polygon-approximation",
    "minAreaRect": "polygon-approximation", "boxPoints": "polygon-approximation", "contourArea": "contour-filtering",
    "arcLength": "contour-filtering", "getPerspectiveTransform": "rectification", "warpPerspective": "rectification",
}


def tool(fn):
    """Wrap a tool so every failure becomes a structured, actionable error (never a fake success)."""
    @functools.wraps(fn)
    def wrapper(*a, **k):
        try:
            out = fn(*a, **k)
            return {"ok": True, **out} if isinstance(out, dict) and "ok" not in out else out
        except paths.PathNotAllowed as e:
            return _err("path_not_allowed", str(e), "use a candidate under candidates/ and corpora generated by generate_visual_test_cases")
        except runner.InfrastructureError as e:
            return _err("infrastructure", str(e), "this is a worker/infra failure, not a failing experiment; retry or reduce workload")
        except FileNotFoundError as e:
            return _err("not_found", str(e), "check the id/path; list saved experiments with compare_implementations or the CLI")
        except (ValueError, KeyError) as e:
            return _err("validation", str(e), "fix the arguments and retry")
        except Exception as e:  # pragma: no cover - last resort, still structured
            return _err("internal", f"{type(e).__name__}: {e}", "report this with the experiment id")
    return wrapper


def _err(kind: str, message: str, hint: str) -> dict:
    return {"ok": False, "error": {"type": kind, "message": message, "hint": hint}}


@tool
def inspect_vision_environment() -> dict:
    return {"environment": runtime.probe(), "workspace_root": str(paths.ROOT),
            "saved_experiments": len(experiments.list_ids())}


@tool
def analyze_vision_pipeline(candidate: str) -> dict:
    """Static inspection only: lists OpenCV calls with file:line. Does not prove runtime behaviour."""
    p = paths.resolve_inside(candidate, paths.CANDIDATES)
    src = p.read_text(encoding="utf-8")
    calls = []
    for node in ast.walk(ast.parse(src)):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and isinstance(node.func.value, ast.Name) \
                and node.func.value.id == "cv2":
            calls.append({"op": node.func.attr, "stage": _STAGE_OF.get(node.func.attr, "other"), "file": p.name, "line": node.lineno})
    calls.sort(key=lambda c: c["line"])
    stages = list(dict.fromkeys(c["stage"] for c in calls))
    return {"candidate": str(p.relative_to(paths.ROOT)), "stages_in_source_order": stages, "calls": calls,
            "has_scan_entrypoint": "def scan(" in src,
            "note": "Static analysis: stage order is by source line, not proof of execution order or behaviour."}


@tool
def generate_visual_test_cases(name: str, categories: list[str] | None = None, seeds: list[int] | None = None,
                               levels: list[int] | None = None, width: int = 640, height: int = 480,
                               params: list[float] | None = None) -> dict:
    if not name.replace("-", "").replace("_", "").isalnum():
        raise ValueError("name must be alphanumeric/-/_")
    paths.ensure_dirs()
    m = synthetic.generate_corpus(paths.CORPORA / name, categories, seeds, levels, width, height, params)
    return {"corpus": f"artifacts/corpora/{name}", "n_cases": m["n_cases"], "generator_version": m["generator_version"],
            "categories": sorted({c["category"] for c in m["cases"]}), "seeds": sorted({c["seed"] for c in m["cases"]}),
            "limits": {"max_cases": synthetic.MAX_CASES, "max_dim": synthetic.MAX_DIM}}


def _brief(rec: dict) -> dict:
    s = rec["summary"]
    return {"experiment_id": rec["experiment_id"], "passed": s["passed"], "n": s["n"], "pass_rate": s["pass_rate"],
            "by_category": {k: round(v["pass_rate"], 3) for k, v in s["by_category"].items()},
            "failure_reasons": s["failure_reasons"], "failed_case_ids": s["failed_case_ids"][:40],
            "acceptance_passed": rec["correctness"]["acceptance_passed"], "median_latency_ms_single_pass": rec["measurements"]["latency_ms_median"],
            "artifact_dir": rec["artifact_dir"], "record": f"artifacts/experiments/{rec['experiment_id']}.json",
            "candidate_sha256": rec["code_revision"][:16]}


@tool
def run_visual_regression_suite(candidate: str, corpus: str, case_ids: list[str] | None = None,
                                config: dict | None = None, timeout_s: int = 120, trace_id: str | None = None) -> dict:
    rec = runner.run_suite(candidate, corpus, label="suite", case_ids=case_ids, config=config, timeout_s=timeout_s, trace_id=trace_id)
    if trace_id:
        experiments.trace(trace_id, "suite_run", candidate=candidate, corpus=corpus, **_brief(rec))
    return _brief(rec)


def _state_from_trace(trace_id: str) -> controller.LoopState:
    st = controller.LoopState(trace_id=trace_id)
    evs = experiments.read_trace(trace_id)
    st.started = evs[0]["ts"] if evs else time.time()
    for e in evs:
        if e["step"] == "decision":
            st.iteration += 1
            if e["action"] == "generate_targeted_cases":
                st.targeted.update(e["args"]["categories"]); st.generated_cases += 24
    return st


@tool
def analyze_visual_failures(experiment_id: str, trace_id: str | None = None) -> dict:
    """Failure patterns + the policy's next action (logged to the trace with its evidence)."""
    rec = experiments.load(experiment_id)
    corp = paths.CORPORA / rec["dataset_id"].split(":", 1)[1]
    man = json.loads((corp / "manifest.json").read_text())
    an = failure_analysis.analyze(rec, man)
    tid = trace_id or rec.get("trace_id") or experiments.new_id("trace")
    st = _state_from_trace(tid)
    dec = controller.decide(an, st)
    experiments.trace(tid, "failure_analysis", experiment_id=experiment_id, n_failed=an["n_failed"],
                      categories=[{k: c[k] for k in ("category", "pass_rate", "dominant_mode", "median_area_ratio")} for c in an["categories"]])
    controller.log_decision(st, dec, experiment_id)
    return {"analysis": an, "next_action": dec, "trace_id": tid, "limits": {"iteration": st.iteration, "max": controller.MAX_ITERATIONS}}


@tool
def reproduce_visual_failure(candidate: str, corpus: str, case_id: str, experiment_id: str | None = None,
                             sweep_params: list[float] | None = None, seed: int = 0) -> dict:
    out = verify.reproduce_failure(candidate, corpus, case_id, experiment_id)
    if sweep_params:
        cat = case_id.split("-")[0]
        out["severity_sweep"] = verify.severity_sweep(candidate, cat, seed, sweep_params)
    return out


@tool
def benchmark_vision_pipeline(candidate: str, corpus: str, warmup: int = 3, repeats: int = 30, threads: int | None = None,
                              trace_id: str | None = None) -> dict:
    rec = benchmark.run_benchmark(candidate, corpus, warmup, repeats, threads, trace_id=trace_id)
    keep = {k: rec[k] for k in ("experiment_id", "environment", "workload", "output_checksum", "correctness")}
    m = rec["measurements"]
    keep["measurements"] = {k: v for k, v in m.items() if k != "raw_latency_ms"}
    keep["runtime"] = {k: rec["runtime"][k] for k in ("opencv_version", "opencv_module_path", "architecture", "platform")}
    keep["raw_data"] = f"artifacts/experiments/{rec['experiment_id']}.json"
    keep["note"] = "LOCAL benchmark; not COOL/Graviton evidence."
    return keep


@tool
def run_cool_graviton_benchmark(candidate: str, corpus: str, repeats: int = 30, threads: int = 4) -> dict:
    """Requires a human-launched COOL instance (config/remote.json). Returns status BLOCKED when unavailable."""
    out = remote.run_cool_graviton_benchmark(candidate, corpus, repeats, threads)
    out.pop("record", None)
    return {"ok": out["status"] == "COMPLETED", **out}


@tool
def compare_implementations(experiment_a: str, experiment_b: str) -> dict:
    a, b = experiments.load(experiment_a), experiments.load(experiment_b)
    if a["kind"] != b["kind"]:
        raise ValueError(f"cannot compare different kinds: {a['kind']} vs {b['kind']}")
    if a["kind"] == "benchmark":
        return benchmark.compare_benchmarks(a, b)
    return verify.compare(a, b)


@tool
def verify_candidate_fix(candidate: str, baseline_experiment_id: str, corpus: str, extra_corpora: list[str] | None = None,
                         extra_baselines: list[str] | None = None, trace_id: str | None = None) -> dict:
    v = verify.verify_candidate(candidate, baseline_experiment_id, corpus, trace_id, extra_corpora, extra_baselines)
    nxt = controller.decide_after_candidate(v)
    if trace_id:
        experiments.trace(trace_id, "post_verification_decision", **nxt)
    slim = {k: v[k] for k in ("verdict", "acceptance_passed", "regressions", "unresolved_cases", "fixed_cases", "experiments", "evidence", "per_corpus") if k in v}
    slim["next_action"] = nxt
    slim["comparison_by_category"] = v.get("comparison", {}).get("by_category")
    return slim
